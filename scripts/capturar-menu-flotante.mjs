import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 375, height: 812 }, deviceScaleFactor: 2 });
await p.goto('http://localhost:3000/app', { waitUntil: 'load' });
await p.evaluate(() => localStorage.clear());
await p.reload({ waitUntil: 'load' });
await p.waitForSelector('text=Siguiente cuidado', { timeout: 15000 });
await p.screenshot({ path: 'docs/revisiones/menu-1-hoy.png' });
await p.getByRole('link', { name: 'Mascotas' }).click();
await p.waitForSelector('text=Tus mascotas');
await p.waitForTimeout(450);
await p.screenshot({ path: 'docs/revisiones/menu-2-mascotas.png' });
await p.getByRole('link', { name: 'Historial' }).click();
await p.waitForSelector('text=Quién hizo qué y cuándo');
await p.waitForTimeout(450);
await p.screenshot({ path: 'docs/revisiones/menu-3-historial.png' });
await p.getByRole('link', { name: 'Yo' }).click();
await p.waitForSelector('text=Quienes cuidan contigo');
await p.waitForTimeout(450);
await p.screenshot({ path: 'docs/revisiones/menu-4-yo.png' });
console.log('scrollWidth', await p.evaluate(() => document.documentElement.scrollWidth));
process.exit(0);
